/* Ask Brightside - frontend. No framework, no build step. */
(function () {
  "use strict";
  var MAX_CHARS = 500, MAX_MSGS = 20, MIN_PER_AUTO = 3;
  var LS = { inbox: "bsd_inbox", stats: "bsd_stats" }, SS = { count: "bsd_msgcount" };

  var $ = function (id) { return document.getElementById(id); };
  var els = {
    messages: $("messages"), form: $("form"), input: $("input"), send: $("send"), chips: $("chips"),
    badge: $("modeBadge"), charCount: $("charCount"), quota: $("quota"), trace: $("trace"),
    minutes: $("minutesSaved"), auto: $("autoCount"), hand: $("handoffCount"),
    inboxList: $("inboxList"), inboxCount: $("inboxCount"), reset: $("reset")
  };

  var kb = null, index = null, history = [], busy = false, apiOnline = true;
  var titles = {}, texts = {};

  function el(tag, cls, text) { var e = document.createElement(tag); if (cls) e.className = cls; if (text != null) e.textContent = text; return e; }
  function load(k, d) { try { return JSON.parse(localStorage.getItem(k)) || d; } catch (e) { return d; } }
  function save(k, v) { try { localStorage.setItem(k, JSON.stringify(v)); } catch (e) {} }
  function msgCount() { return parseInt(sessionStorage.getItem(SS.count) || "0", 10); }
  function bumpCount() { sessionStorage.setItem(SS.count, String(msgCount() + 1)); }

  function setBadge(mode) {
    els.badge.className = "badge " + (mode === "live" ? "badge-live" : "badge-offline");
    els.badge.textContent = mode === "live" ? "● Live AI" : "offline demo mode";
    els.badge.title = mode === "live" ? "Answers generated by an LLM, grounded in the knowledge base"
      : "No AI key configured: answers come from a deterministic knowledge-base match + keyword intent rules";
  }

  function scrollDown() { els.messages.scrollTop = els.messages.scrollHeight; }

  function addUser(text) {
    var m = el("div", "msg user"); m.appendChild(el("div", "bubble", text)); els.messages.appendChild(m); scrollDown();
  }
  function addBot(text, res) {
    var m = el("div", "msg bot"), w = el("div", "bot-wrap");
    w.appendChild(el("div", "bubble", text));
    if (res && res.handoff) w.appendChild(el("span", "handoff-note", "↪ Sent to staff inbox"));
    m.appendChild(w); els.messages.appendChild(m); scrollDown();
  }
  function addTyping() {
    var m = el("div", "msg bot typing"), b = el("div", "bubble"), d = el("span", "dots");
    d.appendChild(el("span")); d.appendChild(el("span")); d.appendChild(el("span"));
    b.appendChild(d); m.appendChild(b); els.messages.appendChild(m); scrollDown(); return m;
  }

  /* ---------- Behind the scenes ---------- */
  function addTrace(message, r) {
    var empty = els.trace.querySelector(".empty"); if (empty) empty.remove();
    var c = el("div", "tcard");
    c.appendChild(el("div", "tmsg", "“" + message + "”"));
    var tags = el("div", "tags");
    var t1 = el("span", "tag i-" + r.intent); t1.innerHTML = "intent: <b></b>"; t1.querySelector("b").textContent = r.intent; tags.appendChild(t1);
    var t2 = el("span", "tag u-" + r.urgency); t2.innerHTML = "urgency: <b></b>"; t2.querySelector("b").textContent = r.urgency; tags.appendChild(t2);
    tags.appendChild(el("span", "tag " + (r.handoff ? "r-hand" : "r-auto"), r.handoff ? "↪ handed off to human" : "✓ auto-answered"));
    tags.appendChild(el("span", "tag r-mode", r.mode === "live" ? (r.provider || "LLM") : "rules engine"));
    c.appendChild(tags);

    c.appendChild(el("div", "tlabel", "Knowledge-base snippets used"));
    var s = el("div", "sources");
    if (!r.sources || !r.sources.length) s.appendChild(el("span", "muted small", "none (off-topic or not covered)"));
    (r.sources || []).forEach(function (id) {
      var d = el("details"), sm = el("summary", null, titles[id] || id);
      sm.appendChild(el("code", null, id)); d.appendChild(sm);
      if (texts[id]) d.appendChild(el("p", null, texts[id]));
      s.appendChild(d);
    });
    c.appendChild(s);
    if (r.handoff && r.staff_draft) {
      c.appendChild(el("div", "tlabel", "Drafted reply for staff"));
      c.appendChild(el("div", "draft", r.staff_draft));
    }
    els.trace.insertBefore(c, els.trace.firstChild);
  }

  /* ---------- Stats + inbox ---------- */
  function renderStats() {
    var st = load(LS.stats, { auto: 0, hand: 0 });
    els.auto.textContent = st.auto; els.hand.textContent = st.hand; els.minutes.textContent = st.auto * MIN_PER_AUTO;
  }
  function renderInbox() {
    var inbox = load(LS.inbox, []);
    els.inboxCount.textContent = inbox.length;
    els.inboxList.innerHTML = "";
    if (!inbox.length) { els.inboxList.appendChild(el("li", "empty", "No handed-off tickets yet.")); return; }
    inbox.forEach(function (t) {
      var li = el("li", "ticket t-" + t.urgency);
      var top = el("div", "ticket-top");
      top.appendChild(el("span", null, "#" + t.id + " · " + t.intent + " · " + t.urgency + " urgency"));
      top.appendChild(el("span", null, new Date(t.at).toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" })));
      li.appendChild(top);
      li.appendChild(el("div", "ticket-msg", t.message));
      if (t.draft) {
        var d = el("details"); d.appendChild(el("summary", null, "View drafted reply"));
        d.appendChild(el("div", "draft", t.draft));
        var a = el("div", "ticket-actions"), copy = el("button", "link-btn", "Copy draft");
        copy.type = "button";
        copy.onclick = function () { if (navigator.clipboard) navigator.clipboard.writeText(t.draft); copy.textContent = "Copied ✓"; };
        var done = el("button", "link-btn", "Mark resolved"); done.type = "button";
        done.onclick = function () { save(LS.inbox, load(LS.inbox, []).filter(function (x) { return x.id !== t.id; })); renderInbox(); };
        a.appendChild(copy); a.appendChild(done); d.appendChild(a); li.appendChild(d);
      }
      els.inboxList.appendChild(li);
    });
  }
  function record(message, r) {
    var st = load(LS.stats, { auto: 0, hand: 0 });
    if (r.handoff) {
      st.hand++;
      var inbox = load(LS.inbox, []);
      var id = (inbox.reduce(function (m, t) { return Math.max(m, t.id); }, 1000)) + 1;
      inbox.unshift({ id: id, at: Date.now(), message: message, intent: r.intent, urgency: r.urgency, draft: r.staff_draft || "" });
      save(LS.inbox, inbox.slice(0, 30));
    } else if (r.sources && r.sources.length) {
      st.auto++;
    }
    save(LS.stats, st); renderStats(); renderInbox();
  }

  /* ---------- Talking to the agent ---------- */
  function localAnswer(message) {
    var r = window.SupportEngine.offlineAnswer(kb, index, message); r.mode = "offline"; return r;
  }

  function ask(message) {
    if (!apiOnline) return Promise.resolve(localAnswer(message));
    return fetch("/api/chat", {
      method: "POST", headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ message: message, history: history.slice(-6) })
    }).then(function (r) {
      return r.json().then(function (j) { if (!r.ok) throw new Error(j && j.error || ("HTTP " + r.status)); return j; });
    }).then(function (j) {
      if (!j || typeof j.reply !== "string") throw new Error("bad response");
      return j;
    }).catch(function (err) {
      if (/too long|required/i.test(String(err && err.message))) throw err;
      apiOnline = false; // server unreachable: run the same rules engine in the browser
      return localAnswer(message);
    });
  }

  function submit(text) {
    text = String(text || "").trim();
    if (!text || busy || !kb) return;
    if (text.length > MAX_CHARS) { addBot("Please keep messages under " + MAX_CHARS + " characters."); return; }
    if (msgCount() >= MAX_MSGS) {
      addBot("You've reached the " + MAX_MSGS + "-message limit for this demo session. Thanks for trying it! Want one for your business? Email www.dave123789@gmail.com.");
      return;
    }
    busy = true; els.send.disabled = true;
    addUser(text); bumpCount(); updateQuota();
    els.input.value = ""; autoSize(); updateCount();
    var typing = addTyping();
    var started = Date.now();
    ask(text).then(function (r) {
      var wait = Math.max(0, 450 - (Date.now() - started));
      setTimeout(function () {
        typing.remove();
        setBadge(r.mode === "live" ? "live" : "offline");
        addBot(r.reply, r); addTrace(text, r); record(text, r);
        history.push({ role: "user", text: text }, { role: "assistant", text: r.reply });
        busy = false; els.send.disabled = false; els.input.focus();
      }, wait);
    }).catch(function (err) {
      typing.remove(); addBot(String(err && err.message || "Something went wrong.")); busy = false; els.send.disabled = false;
    });
  }

  function updateCount() { els.charCount.textContent = els.input.value.length + "/" + MAX_CHARS; }
  function updateQuota() { els.quota.textContent = (MAX_MSGS - msgCount()) + " messages left this session"; }
  function autoSize() { els.input.style.height = "auto"; els.input.style.height = Math.min(120, els.input.scrollHeight) + "px"; }

  els.form.addEventListener("submit", function (e) { e.preventDefault(); submit(els.input.value); });
  els.input.addEventListener("keydown", function (e) { if (e.key === "Enter" && !e.shiftKey) { e.preventDefault(); submit(els.input.value); } });
  els.input.addEventListener("input", function () { updateCount(); autoSize(); });
  els.chips.addEventListener("click", function (e) { var b = e.target.closest(".chip"); if (b) { b.blur(); submit(b.getAttribute("data-q")); } });
  els.reset.addEventListener("click", function () {
    localStorage.removeItem(LS.inbox); localStorage.removeItem(LS.stats); sessionStorage.removeItem(SS.count);
    els.trace.innerHTML = '<p class="empty">Cleared. Send a message to see the agent\'s reasoning.</p>';
    history = []; renderStats(); renderInbox(); updateQuota();
  });

  /* ---------- Boot ---------- */
  fetch("/kb/brightside-kb.json").then(function (r) { return r.json(); }).then(function (data) {
    kb = data; index = window.SupportEngine.buildIndex(kb);
    kb.docs.forEach(function (d) { titles[d.id] = d.title; texts[d.id] = d.text; });
    kb.faqs.forEach(function (f) { titles[f.id] = "FAQ: " + f.q; texts[f.id] = f.a; });
  });
  fetch("/api/chat").then(function (r) { return r.json(); }).then(function (j) {
    setBadge(j && j.llm_configured ? "live" : "offline");
  }).catch(function () { apiOnline = false; setBadge("offline"); });

  renderStats(); renderInbox(); updateCount(); updateQuota();
})();
